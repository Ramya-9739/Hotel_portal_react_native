async function seed() {
  await mongoose.connect("mongodb://localhost:27017/hotelApiDb");
  console.log("Connected to MongoDB.");

  // 1. Update Mango Hotels (1000000001) with rich nearby places
  const updateResult = await HotelProperty.updateMany(
    {
      $or: [
        { hotelPropertyId: "1000000001" },
        { hotelName: /Mango Hotels/i },
        { city: /Bengaluru/i },
      ],
    },
    {
      $set: {
        "nearby.touristPlaces": BENGALURU_TOURIST_PLACES,
        "nearby.shopping": BENGALURU_SHOPPING,
        "nearby.transportation": BENGALURU_TRANSPORT,
      },
    }
  );
  console.log("Updated Bengaluru hotels with nearby curations:", updateResult.modifiedCount);

  // 2. Also ensure TouristDestination collection has all these items
  for (const item of BENGALURU_TOURIST_PLACES) {
    await TouristDestination.findOneAndUpdate(
      { name: item.name },
      {
        destinationId: item.id,
        name: item.name,
        state: "Karnataka",
        city: "Bengaluru",
        description: item.desc,
        category: item.category,
        address: item.address,
        latitude: item.latitude,
        longitude: item.longitude,
        timings: item.timings,
        entryFee: item.price,
        imageLink: item.imageLink,
        images: [item.imageLink],
        rating: item.rating,
        isActive: true,
        isDeleted: false,
      },
      { upsert: true }
    );
  }
  console.log("Seeded TouristDestination collection in MongoDB.");

  const verifyHotel = await HotelProperty.findOne({ hotelPropertyId: "1000000001" });
  console.log("Mango Hotels touristPlaces count:", verifyHotel?.nearby?.touristPlaces?.length);
  console.log("Mango Hotels shopping count:", verifyHotel?.nearby?.shopping?.length);
  console.log("Mango Hotels transportation count:", verifyHotel?.nearby?.transportation?.length);

  await mongoose.disconnect();
}

seed().catch(console.error);
